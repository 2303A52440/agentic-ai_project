"""
Groq LLM client wrapper for MediAssist AI Clinical Platform.
"""

import os
from groq import Groq
from dotenv import load_dotenv
from config import (
    MODEL_NAME,
    MAX_TOKENS,
    DEFAULT_TEMPERATURE,
    BASE_SYSTEM_PROMPT,
    SPECIALTY_PROMPTS,
    MODE_PROMPTS,
)

load_dotenv()


class MedicalLLMClient:
    """Handles clinical decision queries and streaming via Groq LPU."""

    def __init__(self):
        api_key = os.getenv("GROQ_API_KEY")
        if not api_key or api_key == "gsk_your_api_key_here":
            raise ValueError(
                "GROQ_API_KEY not configured. "
                "Add your valid key to the .env file."
            )
        self.client = Groq(api_key=api_key)
        self.model = MODEL_NAME

    def _build_system_prompt(self, specialty: str | None = None, mode: str | None = "patient") -> str:
        """Compose the full clinical system prompt with specialty and persona adjustments."""
        prompt = BASE_SYSTEM_PROMPT

        if mode and mode in MODE_PROMPTS:
            prompt += f"\n\n## Active Persona Profile:\n{MODE_PROMPTS[mode]}"

        if specialty and specialty in SPECIALTY_PROMPTS:
            prompt += f"\n\n## Specialty Focus Domain:\n{SPECIALTY_PROMPTS[specialty]}"

        return prompt

    def get_response(
        self,
        user_message: str,
        chat_history: list[dict] | None = None,
        specialty: str | None = None,
        mode: str | None = "patient",
        temperature: float = DEFAULT_TEMPERATURE,
    ):
        """
        Stream a response from Groq LLM.
        """
        messages = [
            {"role": "system", "content": self._build_system_prompt(specialty, mode)}
        ]

        if chat_history:
            messages.extend(chat_history[-30:])

        messages.append({"role": "user", "content": user_message})

        try:
            completion = self.client.chat.completions.create(
                model=self.model,
                messages=messages,
                max_tokens=MAX_TOKENS,
                temperature=temperature,
                top_p=0.9,
                stream=True,
            )
            return completion
        except Exception as e:
            return f"⚠️ API Inference Error: {str(e)}"

    def generate_soap_note(self, conversation_history: list[dict]) -> str:
        """
        Transform the chat messages into a structured Clinical SOAP Note.
        SOAP = Subjective, Objective, Assessment, Plan.
        """
        if not conversation_history:
            return "No conversation history available to synthesize into a SOAP note."

        conversation_text = "\n".join(
            [f"{m['role'].upper()}: {m['content']}" for m in conversation_history]
        )

        prompt = f"""You are a certified Clinical Informatics Specialist.
Analyze the following patient/doctor dialogue and compile a formal, structured clinical SOAP note:

{conversation_text}

Provide output strictly in this standard medical format:
# 📋 CLINICAL ENCOUNTER SUMMARY (SOAP NOTE)
**Generated by MediAssist AI Engine**

### 1. SUBJECTIVE (S)
- Chief Complaint (CC)
- History of Present Illness (HPI)
- Pertinent Symptoms Reported
- Patient Stated Concerns

### 2. OBJECTIVE (O)
- Self-reported Vital signs or laboratory metrics mentioned (if any)
- Review of reported systems

### 3. ASSESSMENT (A)
- Differential Considerations (Ranked by clinical plausibility)
- Risk Stratification & Red Flag Check

### 4. PLAN & RECOMMENDATIONS (P)
- Recommended Clinical Inquiries for Attending Physician
- Suggested Diagnostic Modalities / Lab Workup to Consider
- Patient Education & Red Flag Return Precautions

*Notice: This SOAP summary is generated by AI for educational/documentation convenience and requires physician verification.*
"""

        try:
            completion = self.client.chat.completions.create(
                model=self.model,
                messages=[
                    {"role": "system", "content": "You are a clinical documentation specialist."},
                    {"role": "user", "content": prompt}
                ],
                max_tokens=1800,
                temperature=0.2,
                stream=False,
            )
            return completion.choices[0].message.content
        except Exception as e:
            return f"Error compiling SOAP note: {str(e)}"
